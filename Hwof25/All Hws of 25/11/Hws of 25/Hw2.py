#Take two numbers as input and print their sum, subtraction, multiplication, and division
a=int(input("Enter 1st value: "))
b=int(input("Enter 2nd value: "))
operator= input("+, -, *, / ")
if operator== "+" : print("Summation",a+b)
if operator== "-" : print("Subtraction",a-b)
if operator== "*" : print("Multiplication",a*b)
if operator== "/" : print("Division",a/b)